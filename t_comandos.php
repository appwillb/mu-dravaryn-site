        <br><p><b>/move</b><br>
          Este comando s&oacute; pode ser utilizado por jogadores com n&iacute;vel
          acima do 50. Serve para fazer um teletransporte para a tela desejada,
          para isso escreva /move mapa. Exemplo: /move lorencia.<br>
          No MU Global voc&ecirc; tem a lista de mapas para o qual voc&ecirc; pode
          usar o comando apertando &quot;M&quot;. Nessa lista voc&ecirc; v&ecirc; o
          lvl necess&aacute;rio para fazer o teletransporte e o quanto gasta
          para o mapa desejado.</p>

        <br><p><b>/Nome do Item</b><br>
          Comando usado para dar uma ajudinha. Voc&ecirc; quer usar certo item,
          mas n&atilde;o tem ele, portanto n&atilde;o sabe se j&aacute; pode
          usar ou quanto falta para usar. tamb&eacute;m deseja saber qto esse
          item tem de ataque ou defesa, etc. Ele abre uma janela com essas informa&ccedil;&otilde;es
          e mostra inclusive os que voc&ecirc; j&aacute; pode usar em branco
          e o que n&atilde;o pode em vermelho. Exemplo: /Heliacal Sword, /Legendary
          Helm, /Chaos Nature Bow. <br>
          O nome do item deve ser colocado usando letras mai&uacute;sculas e
          min&uacute;sculas para poder funcionar, exatamente como o nome do item
          qdo voc&ecirc; coloca o mouse em cima do mesmo. Orbs, asas, an&eacute;is
          e alguns outros itens pode n&atilde;o existir o Help.</p>

        <br><p><b>/guild</b><br>
          Para criar uma guild &eacute; necess&aacute;rio ter o lvl estipulado
          pelo server. Na maioria das vezes n&iacute;vel 100, mas isso depende
          de cada server. Quando estiver no lvl necess&aacute;rio, v&aacute; para
          Davias, no Guild Master, clique nele, d&ecirc; OK, coloque um nome
          para a Guild e crie uma bandeira para ela. O n&ordm; de integrantes
          da sua Guild equivale a 10% do seu lvl. Exemplo: voc&ecirc; &eacute; lvl
          100, cabem 10 pessoas. Lvl 150, cabem 15 pessoas... Caso voc&ecirc; queira
          entrar em uma guild, fique ao lado do GM (Guild Master, Chefe da Guild),
          coloque o ponteiro em cima dele e no chat escreva /guild. <br>
          O GM tamb&eacute;m pode enviar Notices (Aviso), para isso coloque @&gt; antes
          da mensagem. Exemplo: @&gt;Alian&ccedil;a com a Guild X</p>

        <br><p><b>I ou V (Invent&aacute;rio)</b><br>
          Para abrir o seu invent&aacute;rio voc&ecirc; pode apertar &quot;I&quot; ou &quot;V&quot;,
          para fech&aacute;-lo &eacute; a mesma coisa. Nele fica o que voc&ecirc; est&aacute; usando
          (armas, armaduras, an&eacute;is, etc) e tudo o que voc&ecirc; est&aacute; &quot;carregando&quot;. <br>
          CUIDADO!!!: Itens com n&iacute;vel abaixo do +5 e an&eacute;is e pendants
          tem o perigo de &quot;ca&iacute;rem&quot; quando voc&ecirc; morre.
          Itens excellents n&atilde;o caem. Se voc&ecirc; for &quot;PK&quot; (Player
          Killer, Assassino), ter&aacute; mais facilidade de isso acontecer se
          os itens n&atilde;o forem +5 para cima. Quanto maior o seu n&iacute;vel
          d PK, maior ser&aacute; a chance de ca&iacute;rem.</p>

        <br><p><b>C (Charater)</b><br>
          Para abrir/fechar a janela de Stats, aperte &quot;C&quot;. Lugar onde
          voc&ecirc; fica sabendo sobre as condi&ccedil;&otilde;es do seu personagem.
          Exemplo: qual o lvl, quanto de Strenght (For&ccedil;a), Agility (Agilidade),
          Vitality (Vitalidade) e Energy (Energia). Tamb&eacute;m &eacute; onde
          voc&ecirc; pode distribuir os pontos que voc&ecirc; ganha a cada n&iacute;vel
          que sobe. </p>

       <br> <p><b>P (Party)</b><br>
          A tecla &quot;P&quot; ir&aacute; abrir uma janela com os jogadores
          que est&atilde;o em party com voc&ecirc;, mapa e coordenadas que est&atilde;o
          no momento. Para sair da party basta clicar no X ao lado do seu nick.</p>

        <br><p><b>Q, W e E</b><br>
          Teclas usadas para usar po&ccedil;&otilde;es ou outro que escolher.
          Inicialmente os itens que est&atilde;o nessas teclas s&atilde;o po&ccedil;&otilde;es
          de vida, de mana e o ant&iacute;doto, mas voc&ecirc; pode mudar isso.
          Voc&ecirc; pode colocar no lugar de qualquer um deles o Alcohol, Love
          Charm ou Town Teleport. Para fazer isso: abra o invent&aacute;rio,
          coloque o ponteiro do mouse em cima do item sem clicar, segure CTRL+letra.
          Exemplo: colocar Town Teleport na letra E: coloque o ponteiro em cima
          do Town Teleport sem clicar e aperte CTRL+E. O teleporte ser&aacute; usando
          qdo voc&ecirc; apertar a letra E.</p>

        <br><p><b>F1</b><br>
          Abre uma janela de Help com os comandos principais.
          Existem 3 janelas, para tirar tem que ir apertando F1 at&eacute; sumir.</p>

        <br><p><b>F2</b><br>
        Liga/desliga chat comum deixando apenas as mensagens
            privadas (amarelas), Guild (verdes) e Party (azuis). Mensagens escritas
            em aberto n&atilde;o
          aparecer&atilde;o. Muito &uacute;til quando voc&ecirc; quer conversar
          no reservado e est&aacute; no meio da multid&atilde;o.</p>

       <br> <p><b>F3</b><br>
          Liga/desliga a mensagem privada. Voc&ecirc; pode deixar o nick da
          pessoa l&aacute; mesmo que escreva com o nick ao lado do chat ela vai
          em aberto.</p>

       <br> <p><b>F4</b><br>
        Muda o formato do chat.</p>

        <br><p><b>Ctrl</b><br>
          Se voc&ecirc; segurar essa tecla voc&ecirc; pode bater em outros jogadores,
          mas n&atilde;o recomendo voc&ecirc; ficar fazendo isso, pois se voc&ecirc; mata
          outros jogadores voc&ecirc; &eacute; punido com a mudan&ccedil;a de
