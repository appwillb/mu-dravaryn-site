        <p><center>Alguns comandos do MU Online:</center></p><br>
        <p><b>/trade</b><br>
          Coloque o ponteiro do mouse em cima do jogador
            que voc&ecirc; deseja
          fazer trade e escreva o comando no chat. Abrir&aacute; uma janela onde
          voc&ecirc; pode colocar os seus itens ou dinheiro. O Trade serve para
          voc&ecirc; fazer trocas, vendas ou somente para olhar os itens de outro
          jogador.</p>

        <br><p><b>/party</b><br>
          Fa&ccedil;a o mesmo que no trade, mas escreva /party. A Party &eacute; como
          uma uni&atilde;o de at&eacute; 5 jogadores para &quot;ca&ccedil;ar&quot; monstros.
          A experi&ecirc;ncia &eacute; dividida entre eles. Quando &eacute; feito
          a party, fica uns &quot;bot&otilde;es&quot; em cima no canto direito
          onde voc&ecirc; pode ver os jogadores que est&atilde;o por perto, saber
          quanto eles tem de vida e os elfs e magos podem usar algumas magias
