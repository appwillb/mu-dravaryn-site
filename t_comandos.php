       <br> <p><b>Alt</b><br>
          Liga/desliga o nome dos itens que est&atilde;o no ch&atilde;o. Se
          voc&ecirc; segurar essa tecla pode pegar itens que est&atilde;o embaixo
          de outros monstros ou jogadores. Se o item n&atilde;o for seu n&atilde;o
