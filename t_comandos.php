        <br><p><b>Print Screen</b><br>
          Tira um Screenshot da tela. As fotos tiradas v&atilde;o para a pasta
          onde est&aacute; instalado o MU. S&atilde;o gravadas na resolu&ccedil;&atilde;o
          que voc&ecirc; est&aacute; usando para o jogo e em formato JPEG.</p>

